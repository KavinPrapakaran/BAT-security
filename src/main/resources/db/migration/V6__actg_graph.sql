-- BAT security v1.2.0 — ACTG graph persistence.
-- The adaptive cognitive trust graph survives restarts: nodes carry
-- accumulated risk, edges carry relationship weight.

CREATE TABLE IF NOT EXISTS actg_node (
    node_key     TEXT PRIMARY KEY,
    entity_type  TEXT NOT NULL,
    label        TEXT,
    risk         DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    last_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_actg_node_type ON actg_node (entity_type);

CREATE TABLE IF NOT EXISTS actg_edge (
    edge_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key  TEXT NOT NULL,
    target_key  TEXT NOT NULL,
    relation    TEXT NOT NULL,
    weight      DOUBLE PRECISION NOT NULL DEFAULT 1.25,
    observed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_key, target_key, relation)
);

CREATE INDEX IF NOT EXISTS idx_actg_edge_source ON actg_edge (source_key);
CREATE INDEX IF NOT EXISTS idx_actg_edge_target ON actg_edge (target_key);
