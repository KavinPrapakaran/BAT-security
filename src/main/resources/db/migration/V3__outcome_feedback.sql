-- BAT security v3 — LORE outcome feedback

CREATE TABLE IF NOT EXISTS outcome_feedback (
    feedback_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decision_id    UUID NOT NULL,
    realized_risk  DOUBLE PRECISION NOT NULL,
    was_correct    BOOLEAN NOT NULL,
    notes          TEXT,
    recorded_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_outcome_decision ON outcome_feedback (decision_id);
