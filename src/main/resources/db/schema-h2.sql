-- H2 schema for dev/test (sql.init fallback when Flyway is disabled)
CREATE TABLE IF NOT EXISTS signal_observation (
    id UUID PRIMARY KEY, entity_id TEXT NOT NULL, entity_type TEXT NOT NULL,
    evidence_type TEXT NOT NULL, provenance TEXT NOT NULL,
    strength DOUBLE PRECISION NOT NULL, confidence DOUBLE PRECISION NOT NULL,
    explanation TEXT, observed_at TIMESTAMP NOT NULL, created_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS trust_profile (
    entity_id TEXT PRIMARY KEY, entity_type TEXT NOT NULL,
    trust DOUBLE PRECISION NOT NULL, trust_confidence DOUBLE PRECISION NOT NULL,
    observation_count BIGINT NOT NULL DEFAULT 0,
    first_seen_at TIMESTAMP NOT NULL, last_updated_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS trust_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id TEXT NOT NULL, event_type TEXT NOT NULL,
    strength DOUBLE PRECISION NOT NULL, narrative TEXT, occurred_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS decision_log (
    decision_id UUID PRIMARY KEY, entity_id TEXT NOT NULL, entity_type TEXT NOT NULL,
    decision TEXT NOT NULL, recommended_action TEXT NOT NULL,
    risk_score DOUBLE PRECISION NOT NULL, trust_score DOUBLE PRECISION NOT NULL,
    confidence_score DOUBLE PRECISION NOT NULL, business_impact DOUBLE PRECISION NOT NULL,
    rationale TEXT, reasoning_chain TEXT, decision_request TEXT, decided_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS policy_rule (
    rule_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_name TEXT NOT NULL, rule_type TEXT NOT NULL, match_target TEXT NOT NULL,
    action TEXT NOT NULL, priority INT NOT NULL DEFAULT 100,
    organization_id TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE, updated_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS organization_profile (
    organization_id TEXT PRIMARY KEY, name TEXT NOT NULL,
    risk_tolerance DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS asset (
    asset_id TEXT PRIMARY KEY, name TEXT NOT NULL, asset_type TEXT NOT NULL,
    criticality DOUBLE PRECISION NOT NULL, sensitivity DOUBLE PRECISION NOT NULL,
    owner TEXT, dept TEXT, enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS memory_node (
    node_id UUID PRIMARY KEY, node_key TEXT NOT NULL, node_type TEXT NOT NULL,
    label TEXT, properties TEXT NOT NULL DEFAULT '{}',
    base_weight DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    last_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (node_type, node_key)
);
CREATE TABLE IF NOT EXISTS memory_edge (
    edge_id UUID PRIMARY KEY,
    source_node_id UUID NOT NULL, target_node_id UUID NOT NULL,
    relation TEXT NOT NULL, weight DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    last_observed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_node_id, target_node_id, relation)
);
CREATE TABLE IF NOT EXISTS behaviour_baseline (
    entity_id TEXT NOT NULL, feature_name TEXT NOT NULL,
    mean DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    m2 DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    sample_count BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (entity_id, feature_name)
);
CREATE TABLE IF NOT EXISTS outcome_feedback (
    feedback_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decision_id UUID NOT NULL, realized_risk DOUBLE PRECISION NOT NULL,
    was_correct BOOLEAN NOT NULL, notes TEXT,
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS ioc_flag (
    domain TEXT PRIMARY KEY, flag_count BIGINT NOT NULL DEFAULT 1,
    first_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS actg_node (
    node_key TEXT PRIMARY KEY, entity_type TEXT NOT NULL,
    label TEXT, risk DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    last_seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS actg_edge (
    edge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key TEXT NOT NULL, target_key TEXT NOT NULL,
    relation TEXT NOT NULL, weight DOUBLE PRECISION NOT NULL DEFAULT 1.25,
    observed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_key, target_key, relation)
);

